        static string Slug(string name)
        {
            var s = name.Normalize(System.Text.NormalizationForm.FormD);
            var sb = new System.Text.StringBuilder();
            foreach (char c in s)
            {
                if (System.Globalization.CharUnicodeInfo.GetUnicodeCategory(c) == System.Globalization.UnicodeCategory.NonSpacingMark) continue;
                sb.Append(char.IsLetterOrDigit(c) ? c : '_');
            }
            return sb.ToString().Replace("__", "_").Trim('_');
        }

        static void EnsureDir(string path)
        {
            if (AssetDatabase.IsValidFolder(path)) return;
            string parent = Path.GetDirectoryName(path).Replace('\\', '/');
            EnsureDir(parent);
            AssetDatabase.CreateFolder(parent, Path.GetFileName(path));
        }

        static T LoadOrCreate<T>(string path, Action<T> init, List<string> created) where T : ScriptableObject
        {
            var a = AssetDatabase.LoadAssetAtPath<T>(path);
            if (a != null) return a;
            a = ScriptableObject.CreateInstance<T>();
            init(a);
            AssetDatabase.CreateAsset(a, path);
            created.Add(path);
            return a;
        }

        /// <summary>
        /// [VOZ-3] A workshop mode's full voice (TM1 import: the code only carries part of it).
        /// The same table as the menu, so a TM1 and the created style start from the same values.
        /// </summary>
        internal static bool TryModeBase(string mode, ALWTTT.Music.Voice.V8.VoiceV8Params into, out float hardness)
        {
            hardness = 0.5f;
            foreach (var st in Styles)
            {
                if (st.Name != mode) continue;
                var tmp = ScriptableObject.CreateInstance<VoiceProfileSO>();
                try { st.Apply(tmp); tmp.ToV8Params(into); }
                finally { UnityEngine.Object.DestroyImmediate(tmp); }
                hardness = st.Hardness;
                return true;
            }
            return false;
        }

        [MenuItem("ALWTTT/Voz/Crear estilos del taller (VOZ-2)")]
        public static void CreateStyles()
        {
            EnsureDir(StylesDir); EnsureDir(BanksDir); EnsureDir(PalettesDir);
            var created = new List<string>();
            var profiles = new Dictionary<string, VoiceProfileSO>();
            foreach (var st in Styles)
            {
                string slug = Slug(st.Name);
                var zig = LoadOrCreate<SyllableBankSO>($"{BanksDir}/Zigues_{slug}.asset", b =>
                {
                    b.mode = SyllableBankSO.Mode.Zigues; b.lexiconSeed = ZigLexiconSeed; b.hardness = st.Hardness;
                }, created);
                if (st.Syllables.Length > 0)
                    LoadOrCreate<SyllableBankSO>($"{BanksDir}/Silabas_{slug}.asset", b =>
                    {
                        b.mode = SyllableBankSO.Mode.WeightedList;
                        foreach (var (s, w, end) in st.Syllables)
                            b.entries.Add(new SyllableBankSO.Entry { syllable = s, weight = w, isEnd = end });
                    }, created);
                profiles[st.Name] = LoadOrCreate<VoiceProfileSO>($"{StylesDir}/VoiceProfile_{slug}.asset", p =>
                {
                    st.Apply(p);
                    p.engine = VoiceProfileSO.SingerEngine.V8_Workshop;
                    p.gain = st.Gain;
                    p.syllableBank = zig;
                }, created);
            }

            LoadOrCreate<VoiceStylePaletteSO>($"{PalettesDir}/Paleta_Todos_Los_Estilos.asset", pal =>
            {
                foreach (var st in Styles)
                    if (st.Name != "Zig V8")
                        pal.styles.Add(new VoiceStylePaletteSO.Entry { profile = profiles[st.Name], weight = 1f });
            }, created);
            LoadOrCreate<VoiceStylePaletteSO>($"{PalettesDir}/Paleta_Zig_Se_Emborracha.asset", pal =>
            {
                pal.styles.Add(new VoiceStylePaletteSO.Entry { profile = profiles["Borracho"], weight = 70f });
                pal.styles.Add(new VoiceStylePaletteSO.Entry { profile = profiles["Crooner"], weight = 30f });
            }, created);

            AssetDatabase.SaveAssets();
            Debug.Log($"[VOZ-2] Estilos del taller: {created.Count} assets nuevos" +
                      (created.Count > 0 ? ":\n  " + string.Join("\n  ", created) : " (ya existian todos; no se sobrescribe nada)."));
            var first = AssetDatabase.LoadAssetAtPath<UnityEngine.Object>(StylesDir);
            if (first != null) EditorGUIUtility.PingObject(first);
        }
